INK, V, VB, G, GB, GRAY, LINE, RED = '#17171C', '#6F61E8', '#F0EEFE', '#0FBF6E', '#E7FDF2', '#5F5F6B', '#E3E3EA', '#E04848'
FONT = 'Inter Tight, Inter, Arial, Helvetica, sans-serif'


def text(x, y, s, size=26, weight=500, fill=INK, anchor='start'):
    return f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" font-weight="{weight}" fill="{fill}" text-anchor="{anchor}">{e(s)}</text>'


def rect(x, y, w, h, fill='#F5F5F9', stroke='none', r=16, sw=3, dash=''):
    d = f' stroke-dasharray="{dash}"' if dash else ''
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"{d}/>'


def lines(x, y, s, chars, size=26, weight=500, fill=INK, gap=None):
    """Многострочный текст. Возвращает разметку и нижнюю границу."""
    gap = gap or round(size*1.35)
    out = ''
    for row in wrap(s, chars) or ['']:
        out += text(x, y, row, size, weight, fill)
        y += gap
    return out, y-gap


def digit(name, x, y, h=72, color=INK):
    return f'<g transform="translate({x} {y}) scale({h/80})"><path d="{DIGITS[name]}" fill="none" stroke="{color}" stroke-width="6.5" stroke-linecap="round" stroke-linejoin="round"/></g>'


def arrow(x, y, length=30):
    return f'<path d="M{x} {y}H{x+length}M{x+length-10} {y-9}L{x+length} {y}L{x+length-10} {y+9}" fill="none" stroke="{V}" stroke-width="4" stroke-linecap="round" stroke-linejoin="round"/>'


def nest(svg, x, y, w, h):
    """Вкладывает готовую схему со слайда: сами рисунки не дублируются."""
    return re.sub(r'<svg class="[^"]*"', f'<svg x="{x}" y="{y}" width="{w}" height="{h}"', svg, count=1)


def from_art(kind, cls):
    s = next(x for x in slides if x['kind'] == kind)
    return re.findall(rf'<svg class="{cls}".*?</svg>', art['art'](s), re.S)


def wrap_svg(body, h, label):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 {h}" role="img" aria-label="{e(label)}"><title>{e(label)}</title>{body}</svg>'


def rows(cards, y=15, chars=62, numbered=True):
    body = ''
    n = len(cards)
    for i, row in enumerate(cards):
        txt = row[1] if isinstance(row, (list, tuple)) else row
        parts = wrap(txt, chars)
        h = 38*len(parts)+34
        body += rect(15, y, 970, h, r=18)
        if numbered:
            body += f'<circle cx="58" cy="{y+h/2}" r="22" fill="{G if i == n-1 else V}"/>'+text(58, y+h/2+9, str(i+1), 25, 700, INK if i == n-1 else '#FFFFFF', 'middle')
        ty = y+h/2+9-(len(parts)-1)*19
        for p in parts:
            body += text(100 if numbered else 40, ty, p, 27)
            ty += 38
        y += h+12
    return body, y


def prompt_box(tag, prompt, y=15):
    plain = []
    for part in prompt.split('\n'):
        plain += wrap(part, 60)
    h = 44*len(plain)+62
    body = rect(15, y, 970, h, VB, V, 18)+text(40, y+38, tag, 22, 700, V)
    ty = y+80
    for p in plain:
        body += text(40, ty, p, 27, 600)
        ty += 44
    return body, y+h+14


def by(n):
    return slides[n-1]


