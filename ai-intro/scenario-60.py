def inline(s):
    s = e(s, quote=False)
    s = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', s)
    s = re.sub(r'`([^`]+)`', r'<code>\1</code>', s)
    return re.sub(r'\[([^\]]+)\]\(([^)]+)\)', r'<a href="\2">\1</a>', s)


def to_html(md, svgs):
    out, block = [], md.split('\n')
    i = 0
    while i < len(block):
        line = block[i]
        if not line.strip():
            i += 1
        elif line.startswith('### '):
            out.append(f'<h3>{inline(line[4:])}</h3>'); i += 1
        elif line.startswith('## '):
            out.append(f'<h2>{inline(line[3:])}</h2>'); i += 1
        elif line.startswith('# '):
            out.append(f'<h1>{inline(line[2:])}</h1>'); i += 1
        elif line.strip() == '---':
            out.append('<hr>'); i += 1
        elif line.startswith('!['):
            name = re.search(r'\(svg/(.+?)\.svg\)', line).group(1)
            out.append(f'<figure>{svgs[name]}</figure>'); i += 1
        elif line.startswith('|'):
            rows_, i0 = [], i
            while i < len(block) and block[i].startswith('|'):
                rows_.append([c.strip() for c in block[i].strip('|').split('|')]); i += 1
            head = ''.join(f'<th>{inline(c)}</th>' for c in rows_[0])
            body = ''.join('<tr>'+''.join(f'<td>{inline(c)}</td>' for c in r)+'</tr>' for r in rows_[2:])
            out.append(f'<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>')
        elif line.startswith('- '):
            items = []
            while i < len(block) and block[i].startswith('- '):
                items.append(f'<li>{inline(block[i][2:])}</li>'); i += 1
            out.append('<ul>'+''.join(items)+'</ul>')
        else:
            out.append(f'<p>{inline(line)}</p>'); i += 1
    return ''.join(out)


