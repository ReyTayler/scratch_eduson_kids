def goal_cards(s, note_fill, note_stroke, label):
    note, ny = lines(40, 50, s['lead'], 62, 26, 600)
    body = rect(15, 15, 970, ny-15+24, note_fill, note_stroke, 16)+note
    top = ny+36
    columns = []
    for i, (head, items) in enumerate(s['cards']):
        x = 15+i*495
        inner, y = text(x+24, top+42, head, 27, 800), top+84
        for item in items.split('; '):
            first = True
            for part in wrap(item, 33):
                if first:
                    inner += text(x+24, y, '—', 22, 800, V)
                    first = False
                inner += text(x+58, y, part, 22)
                y += 30
            y += 8
        columns.append((x, inner, y))
    bottom = max(c[2] for c in columns)+6
    for x, inner, _ in columns:
        body += rect(x, top, 475, bottom-top, r=18)+inner
    return wrap_svg(body, bottom+15, label)


